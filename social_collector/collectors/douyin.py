from __future__ import annotations

import os
import re
from pathlib import Path
from typing import Any

import requests

from ..models import BaseCollector, CollectorError, ContentMeta, NoteType, Platform
from ..opencli import run_opencli
from ..utils import (
    DEFAULT_UA,
    download_http,
    parse_count,
    require_ytdlp,
    resolve_redirect,
    timestamp_to_text,
    ytdlp_options,
)


class DouyinCollector(BaseCollector):
    platform = Platform.DOUYIN
    supported_domains = ("douyin.com", "iesdouyin.com", "v.douyin.com")

    def _resolve(self, url: str) -> str:
        if "v.douyin.com" in url:
            return resolve_redirect(url, ("douyin.com", "iesdouyin.com"))
        return url

    @staticmethod
    def _aweme_id(url: str) -> str:
        for pattern in (r"/video/(\d+)", r"/share/video/(\d+)", r"[?&]aweme_id=(\d+)"):
            match = re.search(pattern, url)
            if match:
                return match.group(1)
        return ""

    def collect(self, url: str) -> ContentMeta:
        real_url = self._resolve(url)
        meta = ContentMeta(platform=self.platform, url=real_url, note_type=NoteType.VIDEO)

        # Preserve Taiyi's authenticated detail-API path when the user explicitly supplies
        # their own session cookie. No cookie is harvested or generated by this package.
        if os.environ.get("DOUYIN_COOKIE") and self._aweme_id(real_url):
            try:
                if self._from_detail_api(meta):
                    return meta
            except Exception:
                pass

        self._from_ytdlp(meta)
        if not meta.title and not meta.video_url and not meta.image_list:
            raise CollectorError(
                "Douyin metadata could not be extracted. If the post requires sign-in, "
                "export your own Netscape cookie file and set DOUYIN_COOKIE_FILE."
            )
        # A Douyin caption is treated as description rather than a separate title.
        if meta.title and not meta.desc:
            meta.desc = meta.title
        return meta

    def _from_detail_api(self, meta: ContentMeta) -> bool:
        aweme_id = self._aweme_id(meta.url)
        cookie = os.environ.get("DOUYIN_COOKIE", "").strip()
        if not aweme_id or not cookie:
            return False
        response = requests.get(
            "https://www.douyin.com/aweme/v1/web/aweme/detail/",
            params={
                "aweme_id": aweme_id,
                "aid": "6383",
                "device_platform": "web",
                "cookie_enabled": "true",
            },
            headers={
                "User-Agent": DEFAULT_UA,
                "Referer": "https://www.douyin.com/",
                "Accept": "application/json, text/plain, */*",
                "Cookie": cookie,
            },
            timeout=15,
        )
        response.raise_for_status()
        detail = (response.json() or {}).get("aweme_detail") or {}
        if not detail:
            return False
        self._apply_aweme(meta, detail)
        return bool(meta.desc or meta.video_url or meta.image_list)

    def _apply_aweme(self, meta: ContentMeta, detail: dict[str, Any]) -> None:
        meta.desc = detail.get("desc") or ""
        meta.title = meta.desc
        author = detail.get("author") or {}
        meta.author = author.get("nickname") or ""
        meta.author_id = str(author.get("unique_id") or author.get("sec_uid") or "")
        meta.follower_count = parse_count(author.get("follower_count"))
        meta.publish_time = timestamp_to_text(detail.get("create_time"))
        stat = detail.get("statistics") or {}
        meta.liked_count = parse_count(stat.get("digg_count"))
        meta.collected_count = parse_count(stat.get("collect_count"))
        meta.comment_count = parse_count(stat.get("comment_count"))
        meta.share_count = parse_count(stat.get("share_count"))
        meta.play_count = parse_count(stat.get("play_count"))
        video = detail.get("video") or {}
        duration = video.get("duration")
        try:
            meta.video_duration = int(duration) // 1000 if duration else None
        except (TypeError, ValueError):
            pass
        for key in ("download_addr", "play_addr"):
            urls = ((video.get(key) or {}).get("url_list") or [])
            if urls:
                meta.video_url = urls[0]
                break
        cover_urls = ((video.get("cover") or {}).get("url_list") or [])
        if cover_urls:
            meta.cover_url = cover_urls[0]
        images = detail.get("images") or []
        if images:
            meta.note_type = NoteType.NORMAL
            meta.image_list = [
                {"url": urls[0]}
                for image in images[:20]
                if (urls := (image.get("url_list") or []))
            ]
            if meta.image_list:
                meta.cover_url = meta.image_list[0]["url"]
                meta.video_url = ""

    def _from_ytdlp(self, meta: ContentMeta) -> None:
        yt_dlp = require_ytdlp()
        opts = ytdlp_options("douyin")
        with yt_dlp.YoutubeDL(opts) as ydl:
            info = ydl.extract_info(meta.url, download=False)
        if not info:
            return
        meta.title = info.get("title") or ""
        meta.desc = info.get("description") or meta.title
        meta.author = info.get("uploader") or info.get("creator") or ""
        meta.author_id = str(info.get("uploader_id") or info.get("channel_id") or "")
        meta.cover_url = info.get("thumbnail") or ""
        meta.publish_time = timestamp_to_text(info.get("timestamp"))
        meta.video_duration = parse_count(info.get("duration"))
        meta.play_count = parse_count(info.get("view_count"))
        meta.liked_count = parse_count(info.get("like_count"))
        meta.comment_count = parse_count(info.get("comment_count"))
        formats = info.get("formats") or []
        for fmt in formats:
            if fmt.get("vcodec") and fmt.get("vcodec") != "none" and fmt.get("url"):
                meta.video_url = fmt["url"]
                break
        if not meta.video_url:
            meta.video_url = info.get("url") or ""

    def download(self, meta: ContentMeta, output_dir: str | Path) -> list[str]:
        out = Path(output_dir).expanduser().resolve()
        out.mkdir(parents=True, exist_ok=True)
        if meta.image_list:
            paths: list[str] = []
            for index, image in enumerate(meta.image_list, start=1):
                url = image.get("url") or ""
                if not url:
                    continue
                path = download_http(
                    url,
                    out,
                    f"img_{index:02d}.jpg",
                    referer="https://www.douyin.com/",
                )
                if path:
                    paths.append(path)
            return paths

        yt_dlp = require_ytdlp()
        before = {p.resolve() for p in out.rglob("*") if p.is_file()}
        opts = ytdlp_options("douyin", download=True, output_dir=out)
        opts.update({"format": "bestvideo+bestaudio/best", "merge_output_format": "mp4"})
        with yt_dlp.YoutubeDL(opts) as ydl:
            ydl.download([meta.url])
        after = {p.resolve() for p in out.rglob("*") if p.is_file()}
        return [str(path) for path in sorted(after - before)]

    def user_items(self, user: str, limit: int = 20) -> list[dict[str, Any]]:
        data = run_opencli(
            ["douyin", "user-videos", user, "-f", "json", "--limit", str(max(1, limit))],
            timeout=90,
        )
        if not isinstance(data, list):
            return []
        result: list[dict[str, Any]] = []
        for item in data[:limit]:
            aweme_id = str(item.get("aweme_id") or "")
            result.append({
                "content_id": aweme_id,
                "title": item.get("title") or "",
                "create_time": item.get("create_time") or 0,
                "url": f"https://www.douyin.com/video/{aweme_id}" if aweme_id else "",
                "play_url": item.get("play_url") or "",
                "digg_count": parse_count(item.get("digg_count")),
                "collect_count": parse_count(item.get("collect_count")),
                "comment_count": parse_count(item.get("comment_count")),
                "share_count": parse_count(item.get("share_count")),
                "play_count": parse_count(item.get("play_count")),
                "cover_url": item.get("cover_url") or "",
            })
        return result
